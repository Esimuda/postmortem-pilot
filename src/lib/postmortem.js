// Pure, deterministic postmortem builder (no LLM required; Rovo agent adds narrative on top).
const adfToText = (n) => {
  if (!n) return '';
  if (typeof n === 'string') return n;
  if (n.type === 'text') return n.text || '';
  const inner = (n.content || []).map(adfToText).join(n.type === 'doc' ? '\n' : '');
  return ['paragraph', 'heading', 'listItem', 'codeBlock'].includes(n.type) ? inner + '\n' : inner;
};

const ACTION_HINTS = [
  [/timeout|latency|slow/i, 'Add latency SLO alert and dashboard for the affected service', 'detect'],
  [/deploy|release|rollback|migration/i, 'Add canary + automated rollback to the deploy pipeline', 'prevent'],
  [/config|flag|env/i, 'Validate config changes in CI with a schema check', 'prevent'],
  [/memory|oom|cpu|disk/i, 'Set resource limits and saturation alerts', 'detect'],
  [/database|db|query|lock/i, 'Add slow-query logging and index review to runbook', 'mitigate'],
  [/alert|page|noticed|customer report/i, 'Close the detection gap: alert before customers report', 'detect'],
  [/manual|runbook|unclear/i, 'Write or update the runbook for this failure mode', 'mitigate'],
];

function buildPostmortem(issue, comments = [], changelog = []) {
  const f = issue.fields || {};
  const desc = adfToText(f.description).trim();
  const commentTexts = comments.map((c) => ({
    at: c.created, who: c.author?.displayName || 'Unknown', text: adfToText(c.body).trim(),
  }));
  const timeline = [
    { at: f.created, event: `Issue created by ${f.reporter?.displayName || 'Unknown'}` },
    ...changelog.flatMap((h) => (h.items || []).filter((i) => i.field === 'status')
      .map((i) => ({ at: h.created, event: `Status ${i.fromString} → ${i.toString} (${h.author?.displayName || 'Unknown'})` }))),
    ...commentTexts.map((c) => ({ at: c.at, event: `${c.who}: ${c.text.slice(0, 140)}` })),
  ].filter((e) => e.at).sort((a, b) => new Date(a.at) - new Date(b.at));

  const corpus = [f.summary, desc, ...commentTexts.map((c) => c.text)].join('\n');
  const rcLine = corpus.split('\n').find((l) => /root cause|caused by|because/i.test(l));
  const actions = [];
  for (const [re, text, type] of ACTION_HINTS) if (re.test(corpus) && actions.length < 6) actions.push({ text, type });
  if (!actions.length) actions.push({ text: 'Identify and document root cause (needs input)', type: 'prevent' });

  let durationMin = null;
  if (f.created && f.resolutiondate) durationMin = Math.round((new Date(f.resolutiondate) - new Date(f.created)) / 60000);

  return {
    key: issue.key,
    title: `Postmortem: ${f.summary || issue.key}`,
    severity: f.priority?.name || 'Unknown',
    status: f.status?.name || 'Unknown',
    durationMin,
    summary: desc.split('\n').find(Boolean) || 'Unknown - needs input',
    rootCause: rcLine ? rcLine.trim() : 'Unknown - needs input',
    timeline,
    actions,
  };
}

function toMarkdown(pm) {
  return [
    `# ${pm.title}`, '',
    `**Severity:** ${pm.severity} · **Status:** ${pm.status} · **Duration:** ${pm.durationMin ?? '?'} min`, '',
    `## Summary`, pm.summary, '', `## Root cause`, pm.rootCause, '',
    `## Timeline`, ...pm.timeline.map((t) => `- ${t.at} — ${t.event}`), '',
    `## Action items`, ...pm.actions.map((a) => `- [ ] (${a.type}) ${a.text}`), '',
    '_Blameless format. Generated by Postmortem Pilot._',
  ].join('\n');
}

module.exports = { buildPostmortem, toMarkdown, adfToText };
